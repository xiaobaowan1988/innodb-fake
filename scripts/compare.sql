INSERT INTO a VALUES (3,'c',30),(1,'a',10),(2,'b',20),(-5,'neg',-50),(10,'ten',NULL),(7,'seven',30);
SELECT * FROM a ORDER BY id;
SELECT * FROM a ORDER BY id DESC;
SELECT * FROM a WHERE id = 2;
SELECT * FROM a WHERE id = 99;
SELECT * FROM a WHERE id > 2 ORDER BY id;
SELECT * FROM a WHERE id >= 3 AND id < 10 ORDER BY id;
SELECT * FROM a WHERE id < 2 ORDER BY id DESC;
SELECT * FROM a WHERE id BETWEEN -5 AND 1 ORDER BY id;
SELECT * FROM a WHERE n = 30 ORDER BY id;
SELECT * FROM a WHERE n > 15 ORDER BY n, id;
SELECT * FROM a WHERE n IS NULL;
SELECT * FROM a ORDER BY n, id;
SELECT COUNT(*), MIN(id), MAX(id), SUM(n) FROM a;
